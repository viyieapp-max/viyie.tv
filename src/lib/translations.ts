export function getAutoDetectedLanguage(): LangCode {
  // 1. Check Query Param "lang"
  const urlParams = new URLSearchParams(window.location.search);
  const paramLang = urlParams.get('lang')?.toUpperCase();
  if (paramLang && ['ID', 'GB', 'JP', 'CN', 'MY', 'HI'].includes(paramLang)) {
    return paramLang as LangCode;
  }

  // 2. Check LocalStorage (which is set by Admin dropdown)
  const storedLang = localStorage.getItem('viyie_player_language')?.toUpperCase();
  if (storedLang && ['ID', 'GB', 'JP', 'CN', 'MY', 'HI'].includes(storedLang)) {
    return storedLang as LangCode;
  }

  // 3. Fallback to browser locale
  const navLang = navigator.language || (navigator as any).userLanguage || '';
  const cleanLang = navLang.toLowerCase();
  if (cleanLang.includes('id')) return 'ID';
  if (cleanLang.includes('ja') || cleanLang.includes('jp')) return 'JP';
  if (cleanLang.includes('zh') || cleanLang.includes('cn')) return 'CN';
  if (cleanLang.includes('ms') || cleanLang.includes('my')) return 'MY';
  if (cleanLang.includes('hi') || cleanLang.includes('in')) return 'HI';

  return 'GB'; // Fallback to English (United Kingdom)
}
